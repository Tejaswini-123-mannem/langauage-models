"""
Copy deliverables from the local working area to Google Drive.

Why deliverables are produced locally and copied afterwards
-----------------------------------------------------------
The pipeline writes to C:\\lma_work rather than straight to Drive. That
was not an arbitrary choice: an earlier run wrote a 5.78 GB train.jsonl
directly into the Drive folder while syncing was paused, and Drive's
local cache evicted it. The file vanished mid-run and the tokenizer sweep
failed on its second candidate with "Missing corpus files".

A sync-backed folder does not make a file durable until it has uploaded.
Local disk has no such ambiguity. So large outputs are written locally
and published here, once, when syncing is actually running.

What counts as a deliverable
----------------------------
The assignment requires Drive links for datasets, tokenized corpora and
checkpoints, with the links in the README. It does not require the
intermediate deduplication output, which is reproducible by re-running
the pipeline and would add tens of gigabytes to the upload.

So this copies the splits, the tokenizers and the statistics, and leaves
global_dedup, global_near_dedup and corpus/all on local disk.

Phase 2 adds the trained checkpoints, which are required in the same
sentence of the assignment as the datasets and tokenizers. They arrive
from Kaggle rather than from a local stage, so they have to be staged
under <work>/<language>/checkpoints/ before this script can publish them.

Usage
-----
    python publish_deliverables.py --language telugu --dry-run
    python publish_deliverables.py --language telugu
"""

import argparse
import hashlib
import shutil
import sys
import time
import zipfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from language_config import use_utf8_output
from workspace import DRIVE, WORK, Workspace

use_utf8_output()


def deliverables_for(language):
    """
    Return (source, destination, description) for one language.

    Both languages publish the same shape, so the list is built from the
    workspace rather than being written out per language: a language added
    to language_config.py is publishable without editing this script.

    Every tokenizer trained into the final directory is published, not a
    hardcoded set. Telugu delivers two (32k as the primary choice and 16k
    as the documented alternative should Phase 2 favour depth), and a
    language that delivers one should not need a code change to say so.

    Sources that do not exist are reported and skipped rather than
    failing, so the script can be run at any point in the pipeline.
    """

    workspace = Workspace(language)

    splits = workspace.splits
    drive_splits = workspace.drive_splits

    items = [
        (splits / "train.jsonl", drive_splits / "train.jsonl",
         "training split (deliverable 4)"),
        (splits / "validation.jsonl", drive_splits / "validation.jsonl",
         "validation split (deliverable 4)"),
        (splits / "test.jsonl", drive_splits / "test.jsonl",
         "test split (deliverable 4)"),
        (splits / "split_statistics.csv",
         drive_splits / "split_statistics.csv", "split statistics"),
        (splits / "split_summary.json",
         drive_splits / "split_summary.json", "split summary"),
    ]

    tok = workspace.tokenizer_final
    drive_tok = workspace.drive_tokenizer

    labels = {
        ".model": "tokenizer model (deliverable 7)",
        ".vocab": "vocabulary file (deliverable 6)",
        "_metadata.json": "tokenizer training metadata",
    }

    # Sorted so the published order is stable between runs and the log can
    # be diffed against a previous publish.
    for model in sorted(tok.glob("*.model")) if tok.exists() else []:

        stem = model.stem

        for suffix, label in labels.items():
            name = f"{stem}{suffix}"
            items.append((tok / name, drive_tok / name, f"{stem} {label}"))

    # ------------------------------------------------------------------
    # SWEEP CANDIDATES
    # ------------------------------------------------------------------
    # The sweep is evidence, not scratch work. The report's vocabulary
    # argument quotes its fertility and utilisation figures, and a reader
    # checking those numbers needs the models that produced them.
    #
    # It was omitted here originally, which left Telugu's sweep on Drive
    # only because it had been copied by hand, and Assamese's not there at
    # all. Publishing it from the same code makes the two languages
    # symmetric by construction rather than by someone remembering.
    #
    # Only .model, .vocab and metadata are published. The sweep's exported
    # training text (sweep_input.txt) is a multi-gigabyte intermediate
    # regenerated by rerunning the stage, so it is deliberately excluded.
    # ------------------------------------------------------------------

    sweep = workspace.tokenizer_sweep
    drive_sweep = workspace.drive_sweep

    if sweep.exists():

        for path in sorted(sweep.iterdir()):

            if not path.is_file():
                continue

            if path.suffix in (".model", ".vocab") or path.name.endswith(
                ("_metadata.json", "sweep_models.json")
            ):
                items.append(
                    (path, drive_sweep / path.name, f"sweep {path.name}")
                )

    return items


# =============================================================================
# PHASE 2 CHECKPOINTS
# =============================================================================
#
# The assignment asks for checkpoints on Drive with the links in the
# README, in the same breath as the datasets and tokenized corpora. They
# are published from this script rather than copied by hand so that the
# Drive layout is reproduced by one command per language, which is the
# same argument the sweep candidates above are published under.
#
# Only best.pt and final.pt go up. The rolling step_*.pt files exist to
# resume a run within a session and mean nothing once it has finished,
# and latest.pt duplicates whichever step wrote last. The training log
# and console output travel with them: a checkpoint whose loss curve
# cannot be checked is a weight file rather than evidence.
# =============================================================================

CHECKPOINT_FILES = [
    ("best.pt", "best checkpoint by validation loss"),
    ("final.pt", "final checkpoint"),
    ("train_log.jsonl", "training log"),
    ("console.log", "training console output"),
]


def checkpoint_items_for(language):
    """
    Return (source, destination, description) for one language's model.

    Files that are absent are left out rather than reported missing. A
    language whose Phase 2 run has not happened yet should publish its
    Phase 1 deliverables without a column of SKIP lines claiming that
    something went wrong.
    """

    workspace = Workspace(language)
    source_dir = workspace.checkpoints

    if not source_dir.exists():
        print(f"  NOTE: no checkpoints for {language} at {source_dir}")
        return []

    items = []

    for name, label in CHECKPOINT_FILES:

        path = source_dir / name

        if path.exists():
            items.append(
                (
                    path,
                    workspace.drive_checkpoints / name,
                    f"{workspace.language.model_tag} {label}",
                )
            )

    return items


# =============================================================================
# RAW SOURCE FILES
# =============================================================================
#
# The assignment asks for the collected data to be reachable from the
# README, and a grader checking that a corpus really was collected the way
# the report describes needs the files as they arrived, not only the
# cleaned result.
#
# Two shapes of raw source, handled differently
# ---------------------------------------------
# Wikipedia, Wikisource and Sangraha arrive as a handful of large, already
# compressed files (.xml.bz2, .parquet). Those are copied as they are:
# recompressing them would cost time and save nothing.
#
# Internet Archive arrives as one loose .txt per book -- 1,401 files today
# and roughly 3,000 once the remaining Digital Library of India books land.
# Copying thousands of small files into a sync-backed folder is slow, syncs
# unreliably, and leaves a grader with a directory they cannot download in
# one action. So a directory holding more than BUNDLE_THRESHOLD files is
# published as a single .zip instead. Plain OCR text compresses roughly
# four to one, so this shrinks the upload as well.
#
# `chunks/` subdirectories are skipped. They hold extraction intermediates
# written by collect_wiki.py, not collected data, and they are rebuilt by
# rerunning that stage.
# =============================================================================

BUNDLE_THRESHOLD = 50

DERIVED_SUBDIRECTORIES = {"chunks"}


def bundle_directory(source_dir, staging_dir):
    """
    Zip one raw source directory, returning the path to the archive.

    The zip is rebuilt only when missing or older than the newest file it
    should contain, so republishing after collecting more books does not
    recompress a gigabyte that has not changed.
    """

    staging_dir.mkdir(parents=True, exist_ok=True)

    bundle = staging_dir / f"{source_dir.name}.zip"

    files = sorted(p for p in source_dir.rglob("*") if p.is_file())

    if not files:
        return None, 0

    # ----------------------------------------------------------------------
    # Staleness is decided by CONTENTS, not by modification time.
    #
    # An mtime comparison was tried first and silently published a stale
    # bundle. The internetarchive client preserves the server's timestamps
    # on download, so 1,633 books fetched at 16:00 carried mtimes from when
    # Archive built the files -- all older than the zip written at 01:15.
    # The zip looked newer than its own contents, the rebuild was skipped,
    # and the published archive held 1,401 of 3,034 books while reporting
    # "size matches".
    #
    # Comparing the name set is exact and costs only a read of the zip's
    # central directory, which is small and at the end of the file.
    # ----------------------------------------------------------------------

    expected = {p.relative_to(source_dir).as_posix() for p in files}

    if bundle.exists():
        try:
            with zipfile.ZipFile(bundle) as zf:
                if set(zf.namelist()) == expected:
                    return bundle, len(files)

            print(
                f"  REBUILDING {bundle.name}: contents differ "
                f"({len(expected):,} files on disk)"
            )

        except zipfile.BadZipFile:
            print(f"  REBUILDING {bundle.name}: existing archive unreadable")

    # Write to a temporary name first: an interrupted zip that kept the
    # final name would look publishable and would be silently incomplete.
    temp = bundle.with_suffix(".zip.part")

    print(
        f"  BUNDLING {source_dir.name}: {len(files):,} files "
        f"-> {bundle.name} (this takes a minute)"
    )

    start = time.perf_counter()

    with zipfile.ZipFile(
        temp, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=6
    ) as zf:
        for path in files:
            zf.write(path, arcname=path.relative_to(source_dir).as_posix())

    temp.replace(bundle)

    raw_bytes = sum(p.stat().st_size for p in files)
    zip_bytes = bundle.stat().st_size

    print(
        f"           {raw_bytes / 1024**2:,.0f} MB -> "
        f"{zip_bytes / 1024**2:,.0f} MB "
        f"({raw_bytes / max(zip_bytes, 1):.1f}x) "
        f"in {time.perf_counter() - start:.0f}s"
    )

    return bundle, len(files)


def raw_items_for(language, dry_run=False):
    """
    Return (source, destination, description) for one language's raw files.

    Sources that were never collected locally are simply absent from the
    list; copy_one() reports anything missing that was expected.
    """

    workspace = Workspace(language)

    raw = workspace.raw
    drive_raw = workspace.drive_raw

    if not raw.exists():
        print(f"  NOTE: no raw directory for {language} at {raw}")
        return []

    staging = workspace.root / "publish_staging"

    items = []

    for source_dir in sorted(p for p in raw.iterdir() if p.is_dir()):

        payload = [
            p for p in source_dir.rglob("*")
            if p.is_file()
            and not set(p.relative_to(source_dir).parts) & DERIVED_SUBDIRECTORIES
        ]

        if not payload:
            continue

        if len(payload) > BUNDLE_THRESHOLD:

            if dry_run:
                total = sum(p.stat().st_size for p in payload)
                print(
                    f"  WOULD BUNDLE {source_dir.name}: {len(payload):,} "
                    f"files, {total / 1024**2:,.0f} MB -> "
                    f"{source_dir.name}.zip"
                )
                continue

            bundle, count = bundle_directory(source_dir, staging)

            if bundle:
                items.append(
                    (
                        bundle,
                        drive_raw / bundle.name,
                        f"raw {source_dir.name} ({count:,} files, bundled)",
                    )
                )

            continue

        for path in sorted(payload):
            items.append(
                (
                    path,
                    drive_raw / source_dir.name / path.name,
                    f"raw {source_dir.name}/{path.name}",
                )
            )

    return items


def file_hash(path, limit=None):
    """SHA-256 of a file, optionally of only the first `limit` bytes."""

    h = hashlib.sha256()
    read = 0

    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            if limit is not None and read + len(block) > limit:
                h.update(block[: limit - read])
                break
            h.update(block)
            read += len(block)

    return h.hexdigest()


def copy_one(source, destination, description, dry_run, verify):
    """
    Copy one deliverable, skipping it when already present and identical.

    Size is checked first because it is free; the hash is only computed
    when sizes match, since a size mismatch already proves a difference.
    """

    if not source.exists():
        print(f"  SKIP     {description}")
        print(f"           source not found: {source}")
        return "missing"

    size = source.stat().st_size

    if destination.exists() and destination.stat().st_size == size:

        if not verify:
            print(
                f"  PRESENT  {description}  "
                f"({size / 1024**2:,.1f} MB, size matches)"
            )
            return "present"

        if file_hash(source) == file_hash(destination):
            print(
                f"  PRESENT  {description}  "
                f"({size / 1024**2:,.1f} MB, hash verified)"
            )
            return "present"

        print(f"  DIFFERS  {description} - recopying")

    if dry_run:
        print(
            f"  WOULD COPY {description}  ({size / 1024**2:,.1f} MB)"
        )
        print(f"             {source}")
        print(f"          -> {destination}")
        return "would-copy"

    destination.parent.mkdir(parents=True, exist_ok=True)

    # Copy to a temporary name and rename, so an interrupted copy cannot
    # leave a truncated file that later looks like a valid deliverable.
    temp = destination.with_suffix(destination.suffix + ".part")

    start = time.perf_counter()

    shutil.copyfile(source, temp)

    temp.replace(destination)

    elapsed = max(time.perf_counter() - start, 1e-9)

    print(
        f"  COPIED   {description}  {size / 1024**2:,.1f} MB "
        f"in {elapsed:.1f}s ({size / elapsed / 1024**2:.1f} MB/s)"
    )

    return "copied"


def main():

    parser = argparse.ArgumentParser(
        description="Publish deliverables to Google Drive."
    )

    parser.add_argument("--language", required=True)
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument(
        "--verify",
        action="store_true",
        help="Hash-check files that already exist with a matching size.",
    )
    parser.add_argument(
        "--include-raw",
        action="store_true",
        help=(
            "Also publish the collected source files, as downloaded. "
            "Directories holding many small files are bundled into one "
            "zip each; large compressed dumps are copied unchanged."
        ),
    )
    parser.add_argument(
        "--skip-checkpoints",
        action="store_true",
        help=(
            "Do not publish the Phase 2 checkpoints. They are the largest "
            "thing here at roughly 600 MB per language and do not change "
            "between runs, so this is worth having when republishing only "
            "a tokenizer."
        ),
    )
    parser.add_argument(
        "--raw-only",
        action="store_true",
        help="Publish only the raw source files, skipping the deliverables.",
    )

    args = parser.parse_args()

    items = [] if args.raw_only else deliverables_for(args.language)

    # Included by default, unlike the raw sources. Both are large, but a
    # checkpoint is a required deliverable and a missing one is not
    # obvious from the README, whereas nobody grades the absence of a
    # 2 GB Wikipedia dump they did not ask for.
    if not (args.raw_only or args.skip_checkpoints):
        items = items + checkpoint_items_for(args.language)

    if args.include_raw or args.raw_only:
        items = items + raw_items_for(args.language, dry_run=args.dry_run)

    print()
    print("=" * 78)
    print(f"PUBLISHING {args.language.upper()} DELIVERABLES TO DRIVE")
    print("=" * 78)
    print(f"From: {WORK}")
    print(f"To  : {DRIVE}")

    if args.dry_run:
        print("MODE: dry run, nothing will be written")

    print()

    total_bytes = sum(s.stat().st_size for s, _, _ in items if s.exists())

    print(f"Deliverables: {len(items)}   Total: {total_bytes / 1024**3:,.2f} GB")
    print()

    outcomes = {}

    for source, destination, description in items:
        result = copy_one(
            source, destination, description, args.dry_run, args.verify
        )
        outcomes[result] = outcomes.get(result, 0) + 1

    print()
    print("=" * 78)

    for key in ["copied", "present", "would-copy", "differs", "missing"]:
        if outcomes.get(key):
            print(f"  {key:<12} {outcomes[key]}")

    if outcomes.get("missing"):
        print()
        print(
            "  NOTE: missing sources are stages not yet run. Re-run this "
            "script once they exist."
        )

    print()
    print(
        "  REMINDER: files are in the Drive FOLDER but are only in the "
        "CLOUD once syncing has uploaded them. Check the Drive tray icon "
        "before relying on any share link."
    )
    print("=" * 78)


if __name__ == "__main__":
    main()
